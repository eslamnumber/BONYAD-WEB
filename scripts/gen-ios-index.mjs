#!/usr/bin/env node
// Generates docs/ios-call-site-index.md — a precomputed map of the frozen iOS
// app's backend surface: every Service method + its endpoint path, and every
// Model type (Codable field shapes) → exact file:line.
//
// Why: bonayd-ios/ is .gitignore'd and FROZEN, so this map never goes stale.
// Reading it (one small doc) + opening the one mapped file:line range (±15 lines)
// replaces traversing the Swift tree or reading whole files to mirror a backend
// shape. See docs/mapping-protocol.md and CLAUDE.md hard rule 14.
//
// Run locally where the frozen reference exists:  node scripts/gen-ios-index.mjs
// (The committed docs/ios-call-site-index.md is what gets consumed — the folder
//  itself is only needed to REgenerate.)

import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { resolve, join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const IOS_APP = 'bonayd-ios/bonyad-cr-2/App';
const APP_DIR = resolve(ROOT, IOS_APP);
const OUT = resolve(ROOT, 'docs/ios-call-site-index.md');

if (!existsSync(APP_DIR)) {
  console.error(`✗ ${IOS_APP} not found.`);
  console.error('  The frozen iOS reference folder must exist locally to regenerate.');
  process.exit(1);
}

const rel = (f) => relative(ROOT, f).split('\\').join('/');

/** Recursively collect every .swift file under a dir. */
function swiftFiles(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...swiftFiles(full));
    else if (name.endsWith('.swift')) out.push(full);
  }
  return out;
}

const isService = (r) => /\/Services\//.test(r) || /Service\.swift$/.test(r);
const isModel = (r) => /\/Models\//.test(r) || /Models?\.swift$/.test(r);

/** `/projects/\(projectId)/supervisor` → `/projects/:projectId/supervisor`. */
const tidyPath = (p) => p.replace(/\\\(([^)]+)\)/g, ':$1');

/** Service file → [{ func, verb, path, line }] (endpoint call sites). */
function serviceRows(file) {
  const lines = readFileSync(file, 'utf8').split('\n');
  const rows = [];
  let func = '(top-level)';
  let funcLine = 1;
  let verb = '';
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const vc = line.match(/\b(GET|POST|PUT|DELETE|PATCH)\b\s+\/(?:api\/)?[\w{}\-/\\().:?=&]+/);
    if (vc) verb = vc[1];
    const fn = line.match(/func\s+([A-Za-z0-9_]+)\s*[<(]/);
    if (fn) {
      func = fn[1];
      funcLine = i + 1;
    }
    const p = line.match(/path:\s*"([^"]+)"/);
    if (p) {
      rows.push({ func, verb, path: tidyPath(p[1]), line: funcLine });
      verb = '';
    }
  }
  const seen = new Set();
  return rows.filter((r) => {
    const k = `${r.func}|${r.path}`;
    if (seen.has(k)) return false;
    seen.add(k);
    return true;
  });
}

/** Model file → [{ kind, name, conforms, line }] (wire shapes). */
function modelRows(file) {
  const lines = readFileSync(file, 'utf8').split('\n');
  const rows = [];
  for (let i = 0; i < lines.length; i++) {
    const m = lines[i].match(
      /^\s*(?:public\s+|private\s+|internal\s+|final\s+)*(struct|enum|class)\s+([A-Za-z0-9_]+)\s*(?::\s*([^{]+?))?\s*\{?\s*$/,
    );
    if (!m) continue;
    const [, kind, name, conf] = m;
    rows.push({ kind, name, conforms: (conf || '').trim().replace(/\s+/g, ' '), line: i + 1 });
  }
  return rows;
}

const files = swiftFiles(APP_DIR).sort();
const services = [];
const models = [];
for (const f of files) {
  const r = rel(f);
  if (isService(r)) {
    const rows = serviceRows(f);
    if (rows.length) services.push({ file: r, rows });
  }
  if (isModel(r)) {
    const rows = modelRows(f);
    if (rows.length) models.push({ file: r, rows });
  }
}

const appDirs = () =>
  readdirSync(APP_DIR)
    .filter((n) => statSync(join(APP_DIR, n)).isDirectory())
    .sort();

function render() {
  const endpoints = services.reduce((n, s) => n + s.rows.length, 0);
  const types = models.reduce((n, s) => n + s.rows.length, 0);
  const L = [];
  L.push(
    '<!-- GENERATED by scripts/gen-ios-index.mjs — do not hand-edit. Run `pnpm gen:ios-index` to refresh. -->',
  );
  L.push('');
  L.push('# iOS call-site index — backend surface → exact file:line (token-saving map)');
  L.push('');
  L.push("The iOS app at `bonayd-ios/` is **frozen and `.gitignore`'d**, so this precomputed map");
  L.push(
    'never goes stale. It exists so you **never traverse the Swift tree and never read a whole',
  );
  L.push(
    '`*Service.swift` / `*Models.swift` file** just to mirror a backend shape into the web app.',
  );
  L.push('');
  L.push('## How to use this (binding — CLAUDE.md rule 14 + `docs/mapping-protocol.md`)');
  L.push('');
  L.push('1. Find the **Service method** (endpoint path) or **Model type** (field shape) below.');
  L.push(
    '2. `Read` **only that file at that line** (`offset`/`limit` ≈ ±15) to copy the request-body',
  );
  L.push('   fields and the decoded response fields. Do **not** read the whole file.');
  L.push(
    '3. **Services** hold the endpoint path + request/response wiring; **Models** hold the exact',
  );
  L.push('   Codable field names & types. Mirror endpoints into `src/config/endpoints.ts`.');
  L.push(
    '4. Not here? Fall back to one narrow `rg --no-ignore`, then re-run `pnpm gen:ios-index`.',
  );
  L.push('');
  L.push(
    `> Coverage: **${endpoints}** endpoint call sites across **${services.length}** service files · `,
  );
  L.push(`> **${types}** model types across **${models.length}** model files.`);
  L.push('');
  L.push(
    `- **\`App/\` sections:** ${appDirs()
      .map((d) => `\`${d}/\``)
      .join(' · ')}`,
  );
  L.push(
    '- **Endpoints + request/response wiring:** `App/Services/` (+ `*Service.swift` elsewhere).',
  );
  L.push('- **Field shapes (Codable):** `App/Models/` (+ `*Models.swift` elsewhere).');
  L.push('');
  L.push('## Service methods → endpoint path');
  L.push('');
  for (const s of services) {
    L.push(`### \`${s.file}\``);
    L.push('');
    L.push('| Method | Verb | Path | Site |');
    L.push('| --- | --- | --- | --- |');
    for (const r of s.rows)
      L.push(`| \`${r.func}\` | ${r.verb || '—'} | \`${r.path}\` | \`${s.file}:${r.line}\` |`);
    L.push('');
  }
  L.push('## Model types → file:line');
  L.push('');
  for (const m of models) {
    L.push(`### \`${m.file}\``);
    L.push('');
    L.push('| Type | Kind | Conforms | Site |');
    L.push('| --- | --- | --- | --- |');
    for (const r of m.rows)
      L.push(
        `| \`${r.name}\` | ${r.kind} | ${r.conforms ? `\`${r.conforms}\`` : '—'} | \`${m.file}:${r.line}\` |`,
      );
    L.push('');
  }
  return L.join('\n');
}

writeFileSync(OUT, render());
const endpoints = services.reduce((n, s) => n + s.rows.length, 0);
const types = models.reduce((n, s) => n + s.rows.length, 0);
console.log(`✓ ${rel(OUT)}`);
console.log(`  ${endpoints} endpoint sites · ${types} model types`);
