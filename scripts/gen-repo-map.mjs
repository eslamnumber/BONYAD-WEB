#!/usr/bin/env node
// Generates docs/repo-map.md — a precomputed map of THIS Next.js app: routes
// (URL → file), features (+ their api/ endpoint slices), endpoint groups, and
// shared component groups. Deterministic filesystem walk, no LLM tokens.
//
// Why: replaces "let me Explore the repo to find where X lives" with one cheap
// doc read. See docs/mapping-protocol.md. Re-run after adding a route/feature.
//
//   node scripts/gen-repo-map.mjs   (or: pnpm gen:repo-map)

import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { resolve, join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = resolve(ROOT, 'src');
const OUT = resolve(ROOT, 'docs/repo-map.md');

if (!existsSync(SRC)) {
  console.error('✗ src/ not found.');
  process.exit(1);
}

const rel = (f) => relative(ROOT, f).split('\\').join('/');

function walk(dir, pred) {
  const out = [];
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full, pred));
    else if (pred(full)) out.push(full);
  }
  return out;
}

const dirsOf = (dir) =>
  !existsSync(dir)
    ? []
    : readdirSync(dir)
        .filter((n) => statSync(join(dir, n)).isDirectory())
        .sort();

/** src/app/(main)/for-pros/page.tsx → /for-pros */
function routeUrl(file) {
  let p = rel(file).replace(/^src\/app/, '');
  p = p.replace(/\/(page|route|default)\.(tsx?|jsx?)$/, '');
  p = p.replace(/\([^/)]+\)\//g, ''); // strip (route groups)/
  p = p.replace(/\/+/g, '/').replace(/\/$/, '');
  return p === '' ? '/' : p;
}

// --- Routes ---
const routeFiles = walk(join(SRC, 'app'), (f) => /\/(page|route)\.(tsx?|jsx?)$/.test(rel(f)));
const routes = routeFiles
  .map((f) => ({
    url: routeUrl(f),
    file: rel(f),
    kind: /route\.(tsx?|jsx?)$/.test(f) ? 'api' : 'page',
  }))
  .sort((a, b) => a.url.localeCompare(b.url));

// --- Features ---
const FEATURES = join(SRC, 'features');
const features = dirsOf(FEATURES).map((name) => {
  const apiDir = join(FEATURES, name, 'api');
  const apis = walk(
    apiDir,
    (f) => /\.tsx?$/.test(f) && !/\.test\.tsx?$/.test(f) && !/\/index\.tsx?$/.test(rel(f)),
  )
    .map((f) => rel(f).replace(`src/features/${name}/api/`, ''))
    .sort();
  return { name, apis };
});

// --- Endpoint groups (src/config/endpoints.ts) ---
function endpointGroups() {
  const f = join(SRC, 'config', 'endpoints.ts');
  if (!existsSync(f)) return [];
  const groups = [];
  for (const line of readFileSync(f, 'utf8').split('\n')) {
    const m = line.match(/^ {2}([A-Z0-9_]+):\s*\{/);
    if (m) groups.push(m[1]);
  }
  return groups;
}

const componentDirs = dirsOf(join(SRC, 'components'));

function render() {
  const groups = endpointGroups();
  const L = [];
  L.push(
    '<!-- GENERATED by scripts/gen-repo-map.mjs — do not hand-edit. Run `pnpm gen:repo-map` to refresh. -->',
  );
  L.push('');
  L.push('# Repo map — this Next.js app (token-saving navigation index)');
  L.push('');
  L.push('A precomputed map of routes, features, endpoint groups, and shared components so you');
  L.push(
    '**never `Explore`/grep the tree to find where something lives.** Read the row, open the file.',
  );
  L.push('Conventions still live in `docs/` (rule 24) — this answers *where*, not *how*.');
  L.push(
    'Regenerate after adding a route/feature: `pnpm gen:repo-map`. See `docs/mapping-protocol.md`.',
  );
  L.push('');
  L.push(
    `> ${routes.length} routes · ${features.length} features · ${groups.length} endpoint groups · ${componentDirs.length} shared component groups`,
  );
  L.push('');
  L.push('## Routes (URL → file)');
  L.push('');
  L.push('| URL | Kind | File |');
  L.push('| --- | --- | --- |');
  for (const r of routes) L.push(`| \`${r.url}\` | ${r.kind} | \`${r.file}\` |`);
  L.push('');
  L.push('## Features (`src/features/<name>/`) → endpoint slices (`api/`)');
  L.push('');
  L.push('| Feature | `api/` endpoint files |');
  L.push('| --- | --- |');
  for (const f of features)
    L.push(
      `| \`${f.name}\` | ${f.apis.length ? f.apis.map((a) => `\`${a}\``).join(' · ') : '—'} |`,
    );
  L.push('');
  L.push('## Endpoint groups (`src/config/endpoints.ts`)');
  L.push('');
  L.push(groups.map((g) => `\`${g}\``).join(' · ') || '_none parsed_');
  L.push('');
  L.push('## Shared components (`src/components/<group>/`)');
  L.push('');
  L.push(componentDirs.map((d) => `\`${d}/\``).join(' · ') || '_none_');
  L.push('');
  return L.join('\n');
}

writeFileSync(OUT, render());
console.log(`✓ ${rel(OUT)}`);
console.log(
  `  ${routes.length} routes · ${features.length} features · ${componentDirs.length} component groups`,
);
